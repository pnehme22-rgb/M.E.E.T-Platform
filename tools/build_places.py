#!/usr/bin/env python3
"""Build public/assets/js/places.js from tools/places.txt."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "places.txt"
OUT = ROOT / "site" / "assets" / "js" / "places.js"

countries = []
for raw in SRC.read_text(encoding="utf-8").splitlines():
    line = raw.strip()
    if not line or line.startswith("#"):
        continue
    head, _, tail = line.partition("|")
    m = re.match(r"^(.*?)\s*(?:\[(.*)\])?\s*$", head.strip())
    name = m.group(1).strip()
    aliases = [a.strip() for a in (m.group(2) or "").split(",") if a.strip()]
    cities, seen = [], set()
    for c in tail.split(";"):
        c = c.strip()
        if c and c.lower() not in seen:
            seen.add(c.lower())
            cities.append(c)
    countries.append([name, aliases, cities])

countries.sort(key=lambda c: c[0].lower())
names = [c[0] for c in countries]
assert len(names) == len(set(names)), "duplicate country"

body = json.dumps(countries, ensure_ascii=False, separators=(",", ":"))
OUT.write_text(
    "/* Generated by tools/build_places.py from tools/places.txt. Do not edit by hand. */\n"
    "window.MEET_PLACES=" + body + ";\n",
    encoding="utf-8",
)
print("{} countries, {} cities, {:.1f} KB".format(
    len(countries), sum(len(c[2]) for c in countries), OUT.stat().st_size / 1024))
